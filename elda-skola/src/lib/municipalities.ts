export interface Municipality {
  name: string;
  county: string;
}

/** Alla kommuner, sorterade på namn. */
export const MUNICIPALITIES: Municipality[] = Object.entries(BY_COUNTY)
  .flatMap(([county, names]) => names.map((name) => ({ name, county })))
  .sort((a, b) => a.name.localeCompare(b.name, 'sv'));

/**
 * Söker bland kommunerna i tre steg: namn som börjar på sökordet, namn som
 * innehåller det, och sist kommuner vars län matchar. Då föreslås Ronneby före
 * grannkommuner som bara råkar ligga i Blekinge.
 */
export function searchMunicipalities(query: string, limit = 8): Municipality[] {
  const text = query.trim().toLocaleLowerCase('sv');
  if (!text) return MUNICIPALITIES.slice(0, limit);
  const starts: Municipality[] = [];
  const nameContains: Municipality[] = [];
  const countyContains: Municipality[] = [];
  for (const row of MUNICIPALITIES) {
    const name = row.name.toLocaleLowerCase('sv');
    if (name.startsWith(text)) starts.push(row);
    else if (name.includes(text)) nameContains.push(row);
    else if (row.county.toLocaleLowerCase('sv').includes(text)) countyContains.push(row);
  }
  return [...starts, ...nameContains, ...countyContains].slice(0, limit);
}

/** Sant när texten är en av kommunerna i listan (skiftlägesoberoende). */
export function isKnownMunicipality(value: string): boolean {
  const text = value.trim().toLocaleLowerCase('sv');
  return MUNICIPALITIES.some((row) => row.name.toLocaleLowerCase('sv') === text);
}
